using System.IO;
using System.Windows;
using System.Windows.Interop;
using System.Windows.Media;
using System.Windows.Media.Imaging;
using System.Windows.Threading;

namespace RopeShelf.Windows;

public sealed class ClipboardService : IDisposable
{
    private readonly HwndSource source;
    private readonly Dispatcher dispatcher;
    private uint ownSequence;
    private long generation;
    public bool Enabled { get; set; } = true;
    public event Action<DecodedImage>? ImageReceived;
    public event Action<string>? Error;
    private static readonly string[] PrivateFormats = ["ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore",
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "RopeShelf.Generated"];

    public ClipboardService(HwndSource source)
    {
        this.source = source; dispatcher = source.Dispatcher;
        source.AddHook(Hook);
        if (!Native.AddClipboardFormatListener(source.Handle)) throw new InvalidOperationException("无法注册剪贴板监听");
    }
    private nint Hook(nint hwnd, int msg, nint wParam, nint lParam, ref bool handled)
    {
        if (msg == 0x031D && Enabled)
        {
            var sequence = Native.GetClipboardSequenceNumber();
            if (sequence != ownSequence) _ = ReadAsync(sequence, ++generation);
        }
        return 0;
    }
    private async Task ReadAsync(uint sequence, long token)
    {
        for (int attempt = 0; attempt < 5; attempt++)
        {
            if (!Enabled || token != generation || sequence != Native.GetClipboardSequenceNumber()) return;
            try
            {
                var data = Clipboard.GetDataObject();
                if (data == null || data.GetDataPresent(DataFormats.UnicodeText) || data.GetDataPresent(DataFormats.Text)
                    || data.GetDataPresent(DataFormats.FileDrop) || PrivateFormats.Any(f => data.GetDataPresent(f))) return;
                byte[]? bytes = null;
                if (data.GetDataPresent("PNG"))
                {
                    var png = data.GetData("PNG");
                    if (png is MemoryStream stream)
                    { if (stream.Length > ImageCodec.MaxBytes) throw new InvalidDataException("复制图片超过 64 MB"); bytes = stream.ToArray(); }
                    else if (png is byte[] array) bytes = array;
                }
                DecodedImage? decoded;
                if (bytes != null) decoded = await Task.Run(() => ImageCodec.FromBytes(bytes));
                else
                {
                    if (!Clipboard.ContainsImage()) return;
                    BitmapSource? image = Clipboard.GetImage();
                    if (image == null) return;
                    image = RepairOpaqueDib(image); image.Freeze();
                    decoded = await Task.Run(() => ImageCodec.FromBitmap(image));
                }
                if (Enabled && token == generation && sequence == Native.GetClipboardSequenceNumber()) ImageReceived?.Invoke(decoded);
                return;
            }
            catch (System.Runtime.InteropServices.COMException) { await Task.Delay(50 * (attempt + 1)); }
            catch (Exception e) { Error?.Invoke("复制图片未接收：" + e.Message); return; }
        }
        Error?.Invoke("剪贴板正被其他应用占用，本次未能收图");
    }
    public static BitmapSource RepairOpaqueDib(BitmapSource image)
    {
        // DIB's unused alpha bytes can be all zero. Do not apply this to PNG, where transparency is intentional.
        if (image.Format != PixelFormats.Bgra32 && image.Format != PixelFormats.Pbgra32) return image;
        if ((long)image.PixelWidth * image.PixelHeight > ImageCodec.MaxPixels) throw new InvalidDataException("图片尺寸过大");
        var stride = checked(image.PixelWidth * 4); var pixels = new byte[checked(stride * image.PixelHeight)];
        image.CopyPixels(pixels, stride, 0);
        bool anyAlpha = false;
        for (int i = 3; i < pixels.Length; i += 4) if (pixels[i] != 0) { anyAlpha = true; break; }
        if (anyAlpha) return image;
        for (int i = 3; i < pixels.Length; i += 4) pixels[i] = 255;
        return BitmapSource.Create(image.PixelWidth, image.PixelHeight, 96, 96, PixelFormats.Bgra32, null, pixels, stride);
    }
    public async Task CopyAsync(string path)
    {
        var bitmap = await Task.Run(() => ImageCodec.ReadFull(path));
        var png = await Task.Run(() =>
        { var e = new PngBitmapEncoder(); e.Frames.Add(BitmapFrame.Create(bitmap)); using var ms = new MemoryStream(); e.Save(ms); return ms.ToArray(); });
        for (int attempt = 0; attempt < 5; attempt++)
        {
            try
            {
                await dispatcher.InvokeAsync(() =>
                {
                    var data = new DataObject();
                    data.SetData("PNG", new MemoryStream(png));
                    data.SetImage(bitmap);
                    data.SetData("RopeShelf.Generated", new MemoryStream([1]));
                    Clipboard.SetDataObject(data, true);
                    ownSequence = Native.GetClipboardSequenceNumber(); ++generation;
                });
                return;
            }
            catch (System.Runtime.InteropServices.COMException) when (attempt < 4) { await Task.Delay(70 * (attempt + 1)); }
        }
    }
    public void Dispose() { Enabled = false; ++generation; Native.RemoveClipboardFormatListener(source.Handle); source.RemoveHook(Hook); }
}
